def to_yahoo_symbol(code: str, market: str = "IDX") -> str:
    code = code.strip().upper()
    if market.upper() == "IDX":
        if code.endswith(".JK"):
            return code
        return f"{code}.JK"
    return code


def from_yahoo_symbol(symbol: str) -> str:
    return symbol.replace(".JK", "").upper()
